"""Export: dump the dashboard's data contract to report/data.js.

The dashboard emulates BI-tool semantics: it receives the fact table at
invoice grain (mart_orders) plus small reference tables, and computes every
measure client-side so that slicer selections re-filter and recalculate.

The data is embedded as a JS global so the static page also works from disk
(file://), where fetch() of local JSON is blocked by browsers.

Row format for orders (country is an index into the countries array):
    {"date": "2009-12-01", "country": 0, "customer": 13085, "value": 251.7,
     "items": 84}
"""
import json
import sys
from pathlib import Path

import duckdb

DB_PATH = "analytics.duckdb"
OUT_FILE = Path(__file__).parent.parent / "report" / "data.js"


def main() -> None:
    conn = duckdb.connect(DB_PATH, read_only=True)
    try:
        countries = [r[0] for r in conn.execute(
            "SELECT country FROM mart_country ORDER BY revenue DESC"
        ).fetchall()]
        country_idx = {c: n for n, c in enumerate(countries)}

        orders = [
            {
                "date": d.isoformat(),
                "country": country_idx[c],
                "customer": cu,
                "value": v,
                "items": i,
                "lines": ln,
            }
            for d, c, cu, v, i, ln in conn.execute(
                """
                SELECT order_date, country, customer_id, order_value,
                       item_count, line_count
                FROM mart_orders
                ORDER BY order_date, customer_id, country,
                         order_value, item_count, line_count
                """
            ).fetchall()
        ]

        top_products = json.loads(
            conn.execute("SELECT * FROM mart_top_products")
            .df()
            .to_json(orient="records")
        )
        print(f"[export] orders {len(orders):,} rows, "
              f"{len(countries)} countries, {len(top_products)} products")
    finally:
        conn.close()

    payload = {
        "countries": countries,
        "orders": orders,
        "top_products": top_products,
    }
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(
        "// Generated by etl/export.py - do not edit by hand.\n"
        "window.MARTS = " + json.dumps(payload, separators=(",", ":")) + ";\n"
    )
    print(f"[export] wrote {OUT_FILE} ({OUT_FILE.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    sys.exit(main())
